import { useState } from "react";
import { GitBranch, GitPullRequest, Search, Sparkles, Timer } from "lucide-react";
import StatusIcon, { Pill } from "../components/StatusIcon.jsx";
import { MIGRATIONS, NOW, RUN_STATUS, STAGES, runStatusAt, stageStatusAt } from "../data/mock.js";
import { Link } from "../router.jsx";
import { cx, fmtDuration } from "../lib.js";

const FILTERS = [
  { id: "all", label: "All" },
  { id: "running", label: "Running", match: (s) => s === "running" || s === "recovering" },
  { id: "blocked", label: "Blocked", match: (s) => s === "blocked" },
  { id: "finished", label: "Finished", match: (s) => ["passed", "failed", "rolled_back"].includes(s) },
];

function resolve(m) {
  if (!m.live) return { status: m.status, stages: m.stages };
  return { status: runStatusAt(NOW), stages: STAGES.map((s) => stageStatusAt(s.id, NOW)) };
}

export default function Migrations() {
  const [filter, setFilter] = useState("all");
  const [q, setQ] = useState("");

  const rows = MIGRATIONS.map((m) => ({ ...m, ...resolve(m) })).filter((m) => {
    const f = FILTERS.find((x) => x.id === filter);
    if (f?.match && !f.match(m.status)) return false;
    if (q && !`${m.title} ${m.branch} ${m.id}`.toLowerCase().includes(q.toLowerCase())) return false;
    return true;
  });

  const counts = Object.fromEntries(
    FILTERS.map((f) => [f.id, MIGRATIONS.map((m) => resolve(m).status).filter((s) => !f.match || f.match(s)).length]),
  );

  return (
    <>
      <div className="tabs">
        {FILTERS.map((f) => (
          <button key={f.id} className={cx("tab", { active: filter === f.id })} onClick={() => setFilter(f.id)}>
            {f.label}
            <span className="count">{counts[f.id]}</span>
          </button>
        ))}
      </div>

      <div className="toolbar">
        <label className="filter">
          <Search size={15} />
          <input placeholder="Filter migrations" value={q} onChange={(e) => setQ(e.target.value)} />
        </label>
      </div>

      <div className="table">
        <div className="tr th">
          <div>Status</div>
          <div>Migration</div>
          <div>Generated by</div>
          <div>Stages</div>
          <div />
        </div>
        {rows.map((m) => {
          const rs = RUN_STATUS[m.status];
          return (
            <div className="tr" key={m.id}>
              <div className="cell-status">
                <Pill tone={rs.tone}>
                  <StatusIcon status={m.status === "passed" ? "succeeded" : m.status === "recovering" ? "running" : m.status} size={14} agent={m.status === "recovering"} />
                  {rs.label}
                </Pill>
                <span className="muted small">
                  <Timer size={12} /> {fmtDuration(m.duration)}
                </span>
                <span className="muted small">{m.when}</span>
              </div>
              <div className="cell-title">
                <Link to={`/migrations/${m.id}`} className="row-title">
                  {m.title}
                </Link>
                <span className="row-meta">
                  <span className="mono">#{m.id}</span>
                  <span>
                    <GitBranch size={12} /> {m.branch}
                  </span>
                  <span>
                    <GitPullRequest size={12} /> !{m.pr}
                  </span>
                </span>
                {m.tags?.length > 0 && (
                  <span className="row-tags">
                    {m.tags.map((tg) => (
                      <Pill key={tg} tone="green" className="tag">
                        {tg}
                      </Pill>
                    ))}
                  </span>
                )}
              </div>
              <div className="cell-by">
                <span className="avatar violet">
                  <Sparkles size={12} />
                </span>
                <span>{m.generatedBy}</span>
              </div>
              <div className="cell-stages">
                {m.stages.map((st, i) => (
                  <StatusIcon key={STAGES[i].id} status={st} size={20} title={`${STAGES[i].name}: ${st.replace("_", " ")}`} agent={STAGES[i].id === "recover" || STAGES[i].id === "agents"} />
                ))}
              </div>
              <div className="cell-actions">
                <Link to={`/migrations/${m.id}`} className="btn btn-ghost">
                  Open
                </Link>
              </div>
            </div>
          );
        })}
        {rows.length === 0 && <div className="tr empty-row">No migrations match.</div>}
      </div>
    </>
  );
}
